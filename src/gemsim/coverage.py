"""SECS-II message coverage table, generated from the equipment's dispatch table.

``python -m gemsim coverage`` prints it; ``--write docs/message_coverage.md``
refreshes the committed copy, and a test fails when that copy is out of date.
"""

from __future__ import annotations

from .gem.equipment import EQUIPMENT_PRIMARIES, HOST_PRIMARIES

HEADER = """# SECS-II message coverage

Generated by `python -m gemsim coverage --write docs/message_coverage.md` from
`HOST_PRIMARIES` and `EQUIPMENT_PRIMARIES` in `src/gemsim/gem/equipment.py`.
`tests/test_coverage.py` fails if this file and the code disagree.

H->E: the host sends the primary and the equipment replies. E->H: the equipment
sends the primary. Stream 9 messages have no reply. Every primary also has an
SxF0 abort path (off-line or not communicating), which is not listed.

| Primary | Reply | Name | Direction |
|---|---|---|---|
"""


def coverage_rows() -> list[tuple[str, str, str, str]]:
    """(primary, reply, name, direction) for every implemented primary, sorted by S, F."""
    rows: dict[tuple[int, int], tuple[str, str, str, str]] = {}
    for (s, f), (name, _) in HOST_PRIMARIES.items():
        rows[(s, f)] = (f"S{s}F{f}", f"S{s}F{f + 1}", name, "H->E")
    for (s, f), name in EQUIPMENT_PRIMARIES.items():
        reply = "-" if s == 9 else f"S{s}F{f + 1}"
        if (s, f) in rows:
            primary, reply, host_name, _ = rows[(s, f)]
            rows[(s, f)] = (primary, reply, host_name, "H->E, E->H")
        else:
            rows[(s, f)] = (f"S{s}F{f}", reply, name, "E->H")
    return [rows[key] for key in sorted(rows)]


def coverage_markdown() -> str:
    body = "".join(f"| {p} | {r} | {n} | {d} |\n" for p, r, n, d in coverage_rows())
    return HEADER + body
